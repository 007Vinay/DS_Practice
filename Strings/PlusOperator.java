package Strings;

public class PlusOperator {
    public static void main(String[] args) {
        String s = "bhakti";
        s= s +" hi sakti hai";
        s=10+s;
        s=s+10;
        s+=10;
        s+= 'a';
        s+= '\n';
        s+= 'n';
        System.out.println(s);

        System.out.println("Raghav"+10+20);
        System.out.println(10+20+"Krutika"+20);
        System.out.println('A'+2+"Isha");
    }
}
